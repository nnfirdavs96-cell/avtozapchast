<?php
/**
 * Ручной провайдер: оплату отмечает владелец (Фаза 3b).
 *
 * Это не заглушка «на будущее», а рабочий способ, которым магазин живёт прямо сейчас:
 * наличные при получении, перевод на карту, оплата в офисе. Раньше эти деньги нигде
 * не фиксировались — заказ был либо «доставлен», либо нет, а получены ли деньги,
 * знал только владелец.
 *
 * Заодно на нём проверяется весь остальной контур — журнал транзакций, статусы,
 * идемпотентность, — без единого банка. Когда придёт эквайринг, отлаживать придётся
 * только адаптер, а не всё вокруг него.
 */

require_once __DIR__ . '/PaymentProvider.php';

class ManualProvider implements PaymentProvider
{
    public function id(): string    { return 'manual'; }
    public function title(): string { return 'Оплата вручную (наличные, перевод)'; }

    /** Всегда готов: никаких ключей и договоров не требует. */
    public function isReady(): bool { return true; }

    public function startPayment(array $order): array
    {
        // Никуда не уводим: деньги придут вне сайта, владелец отметит это в админке.
        return ['message' =>
            'Заказ принят. Оплату подтвердит менеджер после получения денег.'];
    }

    /**
     * Внешних подтверждений у ручного способа не бывает — платёж отмечается
     * из админки. Отвечаем отказом, чтобы случайный запрос на webhook не был
     * истолкован как подтверждение оплаты.
     */
    public function handleCallback(array $request, string $rawBody): array
    {
        return ['ok' => false, 'error' => 'Ручной способ оплаты не принимает подтверждений извне.'];
    }
}
