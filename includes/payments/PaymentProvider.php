<?php
/**
 * Контракт платёжного провайдера (Фаза 3b).
 *
 * Смысл интерфейса ровно тот же, что у слоя каталога: чекаут не должен знать, какой
 * банк принимает деньги. Смена банка — это новый класс, а не правки в оформлении
 * заказа. В Таджикистане выбор эквайринга ограничен и может смениться, поэтому
 * привязываться к одному нельзя.
 *
 * ЧТО МОЖНО БЫЛО ЗАЛОЖИТЬ ЗАРАНЕЕ: сам контракт, журнал транзакций, идемпотентность
 * подтверждений, сверка суммы, статусы заказа.
 * ЧЕГО НЕЛЬЗЯ: формат запроса, схему подписи, коды ответов конкретного банка. Это
 * описано в его документации, и угадывать её — значит написать абстракцию, которую
 * всё равно придётся переделать.
 */

interface PaymentProvider
{
    /** Машинное имя: `manual`, `alif`, `eskhata`. Оно же пишется в journal. */
    public function id(): string;

    /** Название для админки и чекаута. */
    public function title(): string;

    /** Готов ли провайдер принимать платежи (ключи заполнены, включён). */
    public function isReady(): bool;

    /**
     * Начать оплату заказа.
     *
     * Возвращает ['redirect' => URL] — куда отправить покупателя,
     * либо ['message' => текст] — если оплата не требует ухода с сайта
     * (например, владелец отметит её вручную).
     */
    public function startPayment(array $order): array;

    /**
     * Разобрать подтверждение от банка.
     *
     * Здесь же проверяется ПОДПИСЬ: подтверждение приходит по открытому URL, и без
     * проверки подписи любой смог бы объявить чужой заказ оплаченным.
     *
     * Возвращает ['ok' => bool, 'order_id' => int, 'external_id' => string,
     *             'amount' => float, 'status' => 'succeeded'|'failed'|'pending',
     *             'error' => ?string]
     */
    public function handleCallback(array $request, string $rawBody): array;
}
